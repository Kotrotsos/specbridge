"use server";

import { prisma } from "@/lib/prisma";
import { auth } from "@clerk/nextjs/server";
import { revalidatePath } from "next/cache";
import {
    uploadToR2,
    deleteFromR2,
    generateProjectStorageKey,
    getMimeType,
} from "@/lib/r2";
import { extractText, getFileType } from "@/lib/text-extraction";

// Types
export interface ProjectSourceDocumentData {
    id: string;
    projectId: string;
    fileName: string;
    fileType: string;
    fileSize: number;
    status: string;
    extractionStatus: string;
    extractedText: string | null;
    extractedFeatures: ExtractedFeature[] | null;
    extractedSpecs: ExtractedSpecGroup[] | null;
    error: string | null;
    createdAt: string;
}

export interface ExtractedFeature {
    name: string;
    description: string;
    documentContext: string;
}

export interface ExtractedSpec {
    name: string;
    initialDescription: string;
    documentContext: string;
}

export interface ExtractedSpecGroup {
    featureName: string;
    specifications: ExtractedSpec[];
}

export interface AutoGeneratedStats {
    features: number;
    specifications: number;
    documents: number;
}

/**
 * Get all source documents for a project
 */
export async function getProjectSourceDocuments(
    projectId: string
): Promise<ProjectSourceDocumentData[]> {
    const { userId, orgId } = await auth();
    if (!userId) throw new Error("Unauthorized");

    // Verify access to project
    const project = await prisma.project.findUnique({
        where: { id: projectId },
    });

    if (!project) throw new Error("Project not found");

    const hasAccess =
        project.userId === userId ||
        (orgId && project.organizationId === orgId);
    if (!hasAccess) throw new Error("Unauthorized");

    const documents = await prisma.projectSourceDocument.findMany({
        where: { projectId },
        orderBy: { createdAt: "desc" },
    });

    return documents.map((doc) => ({
        id: doc.id,
        projectId: doc.projectId,
        fileName: doc.fileName,
        fileType: doc.fileType,
        fileSize: doc.fileSize,
        status: doc.status,
        extractionStatus: doc.extractionStatus,
        extractedText: doc.extractedText,
        extractedFeatures: doc.extractedFeatures as ExtractedFeature[] | null,
        extractedSpecs: doc.extractedSpecs as ExtractedSpecGroup[] | null,
        error: doc.error,
        createdAt: doc.createdAt.toISOString(),
    }));
}

